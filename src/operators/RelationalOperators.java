package operators;

public class RelationalOperators {
	
	public static void main(String[] args) {
		int a= 10;
		int b=20;
		
		// it is used for comparison
		//it will return boolean value
		System.out.println(a==b);
		System.out.println(a!=b);
		System.out.println(a>b);
		System.out.println(a<b);
		System.out.println(a<=b);
		System.out.println(a>=b);
		
		
	} 

}
